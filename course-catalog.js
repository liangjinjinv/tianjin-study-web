(() => {
  'use strict';
  const courses = window.TJ_COURSE;
  const sectionsBySubject = new Map(courses.map(course => [course.name, course.chapters.flatMap((chapter, chapterIndex) => chapter.lessons.map((lesson, lessonIndex) => Object.freeze({
    ...lesson, subject: course.name, chapter: chapter.title, chapterIndex, lessonIndex
  })))]));
  const sectionById = new Map([...sectionsBySubject.values()].flat().map(section => [section.id, section]));
  const sections = subject => (sectionsBySubject.get(subject) || []).slice();
  const byId = id => sectionById.get(id);
  const samples = window.TJ_SAMPLES;
  const sampleQuestion = id => {
    const section = byId(id), sample = Object.hasOwn(samples, id) ? samples[id] : null;
    if (!section || !sample) return null;
    return {id:'course-'+id, section:id, subject:section.subject, topic:section.title, prompt:sample.question, options:sample.options.slice(), type:'single', correct:sample.answer, answer:sample.options[sample.answer], explain:sample.explanation, source:'built'};
  };
  window.StudyCatalog = Object.freeze({courses, sections, byId, samples, sampleQuestion});
})();
